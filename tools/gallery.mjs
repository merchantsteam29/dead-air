// Every creature and a few crew in bright light, plus a view from above. node tools/gallery.mjs
import { open, sleep } from './harness.mjs';
import { spawn } from 'child_process';
import path from 'path'; import { fileURLToPath } from 'url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const port = 8600 + Math.floor(Math.random() * 300);
const srv = spawn(process.execPath, ['serve.js'], { cwd: root, env: { ...process.env, PORT: port }, stdio: 'ignore' });
process.env.SH_URL = `http://localhost:${port}/`;
await sleep(500);
const { ev, shot, done, url, send } = await open(import.meta.url);
await send('Page.navigate', { url: url + '&nomic&autostart' });
await sleep(6000);
const g = 'window.__da.game';
await ev(`const g = ${g}; g.hemi.intensity = 2.5; g.scene.fog.density = 0.005; g.over = true;
  const W = g.world; const x0 = W.van.x - 7, z0 = W.van.z - 9;
  const kinds = ['chair','tv','flamingo','wardrobe','balloon','dancer','applause','hand'];
  kinds.forEach((k, i) => { const t = g.things.spawn(k, x0 + i * 2, z0, { yaw: 0, y: k === 'balloon' ? 1.9 : 0 }); if (k==='wardrobe'||k==='tv'||k==='dancer') t.s = 1; t.model = null; });
  g.things.list.forEach(t => { if (t.kind==='wardrobe'||t.kind==='dancer') { t.s = 1; } });
  window.__x0 = x0; window.__z0 = z0;
  g.camera.position.set(x0 + 7, 1.6, z0 + 6); g.camera.rotation.set(-0.12, 0, 0);
  g.frame = function(dt){ this.time += dt; this.things.applySnap(this.things.snap()); this.things.render(dt); this.items.render(dt); };`);
await sleep(2500);
await shot('1-creatures');
await ev(`const g = ${g}; g.camera.position.set(__x0 + 13, 1.9, __z0 + 2.6); g.camera.rotation.set(-0.2, 0.25, 0);`);
await sleep(1500);
await shot('2-close');
await ev(`const g = ${g}; const W = g.world; g.camera.position.set(W.W/2, 70, W.H/2 + 10); g.camera.rotation.set(-1.45, 0, 0); g.camera.far = 300; g.camera.updateProjectionMatrix();`);
await sleep(1500);
await shot('3-above');
srv.kill(); await done();
